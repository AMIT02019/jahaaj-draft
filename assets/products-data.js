// Helper: Get Product by ID or Slug
function getJahaajProduct(idOrSlug) {
  if (!idOrSlug) return null;
  const clean = idOrSlug.toLowerCase().trim();
  return window.JAHAAJ_PRODUCTS.find(p => p.id.toLowerCase() === clean || p.slug.toLowerCase() === clean) || null;
}

// Helper: Get Products by Species
function getJahaajProductsBySpecies(species) {
  if (!species || species === 'all') return window.JAHAAJ_PRODUCTS;
  const clean = species.toLowerCase().trim();
  return window.JAHAAJ_PRODUCTS.filter(p => p.species.toLowerCase() === clean);
}

