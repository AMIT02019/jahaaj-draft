// Global Query Helpers
function getJahaajProduct(id) {
  if (!id) return null;
  return window.JAHAAJ_PRODUCTS.find(p => p.id === id || p.slug === id) || null;
}

function getJahaajProductsBySpecies(species) {
  if (!species) return window.JAHAAJ_PRODUCTS;
  return window.JAHAAJ_PRODUCTS.filter(p => p.species === species);
}

